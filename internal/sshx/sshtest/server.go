// Package sshtest is an in-process SSH server for tests. It supports public
// key and certificate auth, exec sessions (handled by a Go func, which may run
// a real shell), direct-tcpip forwarding, keepalive replies that can be
// switched off, and being stopped and restarted on the same port.
//
// Unit tests use it instead of real hosts (CLAUDE.md "Testing").
package sshtest

import (
	"crypto/ed25519"
	"crypto/rand"
	"encoding/binary"
	"errors"
	"fmt"
	"io"
	"net"
	"strconv"
	"sync"
	"sync/atomic"
	"testing"

	"golang.org/x/crypto/ssh"
)

// ExecFunc handles one exec request. It returns the exit status.
type ExecFunc func(cmd string, stdin io.Reader, stdout, stderr io.Writer) int

// Server is a test SSH server. Configure the exported fields before Start.
type Server struct {
	// HostKey is generated by NewServer.
	HostKey ssh.Signer
	// AuthorizedKeys may log in. CertAuthority, if set, signs user
	// certificates that may log in too.
	AuthorizedKeys []ssh.PublicKey
	CertAuthority  ssh.PublicKey
	// Exec handles exec requests; nil exits 127.
	Exec ExecFunc
	// AllowForwarding enables direct-tcpip; DialTarget opens the target
	// (default net.Dial).
	AllowForwarding bool
	DialTarget      func(addr string) (net.Conn, error)
	// IgnoreKeepalive makes the server stop answering global requests, as a
	// hung or partitioned host would.
	IgnoreKeepalive atomic.Bool

	// Addr is host:port once started.
	Addr string

	t       testing.TB
	mu      sync.Mutex
	ln      net.Listener
	conns   map[net.Conn]bool
	open    int
	maxOpen int
	execs   []string
	logins  []string
}

// NewServer returns a server with a fresh ed25519 host key.
func NewServer(t testing.TB) *Server {
	t.Helper()
	return &Server{HostKey: NewSigner(t), conns: map[net.Conn]bool{}, t: t}
}

// NewSigner returns a fresh ed25519 signer.
func NewSigner(t testing.TB) ssh.Signer {
	t.Helper()
	_, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	s, err := ssh.NewSignerFromKey(priv)
	if err != nil {
		t.Fatal(err)
	}
	return s
}

// Start listens on 127.0.0.1 (a random port the first time, the same port
// after Stop) and serves until Stop or the end of the test.
func (s *Server) Start() {
	s.t.Helper()
	addr := s.Addr
	if addr == "" {
		addr = "127.0.0.1:0"
	}
	ln, err := net.Listen("tcp", addr)
	if err != nil {
		s.t.Fatal(err)
	}
	s.mu.Lock()
	s.ln = ln
	s.Addr = ln.Addr().String()
	s.mu.Unlock()
	go s.serve(ln)
	s.t.Cleanup(s.Stop)
}

// Port returns the listening port.
func (s *Server) Port() int {
	_, p, _ := net.SplitHostPort(s.Addr)
	n, _ := strconv.Atoi(p)
	return n
}

// Stop closes the listener and every connection, as if sshd went away.
func (s *Server) Stop() {
	s.mu.Lock()
	if s.ln != nil {
		s.ln.Close() //nolint:errcheck,gosec
		s.ln = nil
	}
	for c := range s.conns {
		c.Close() //nolint:errcheck,gosec
	}
	s.mu.Unlock()
}

// MaxConcurrentChannels is the largest number of channels open at once.
func (s *Server) MaxConcurrentChannels() int {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.maxOpen
}

// Execs returns the commands received so far.
func (s *Server) Execs() []string {
	s.mu.Lock()
	defer s.mu.Unlock()
	return append([]string(nil), s.execs...)
}

// Logins returns the user names that authenticated.
func (s *Server) Logins() []string {
	s.mu.Lock()
	defer s.mu.Unlock()
	return append([]string(nil), s.logins...)
}

func (s *Server) config() *ssh.ServerConfig {
	checker := &ssh.CertChecker{
		IsUserAuthority: func(auth ssh.PublicKey) bool {
			return s.CertAuthority != nil && string(auth.Marshal()) == string(s.CertAuthority.Marshal())
		},
		UserKeyFallback: func(_ ssh.ConnMetadata, key ssh.PublicKey) (*ssh.Permissions, error) {
			for _, k := range s.AuthorizedKeys {
				if string(k.Marshal()) == string(key.Marshal()) {
					return &ssh.Permissions{}, nil
				}
			}
			return nil, errors.New("unknown key")
		},
	}
	cfg := &ssh.ServerConfig{PublicKeyCallback: checker.Authenticate}
	cfg.AddHostKey(s.HostKey)
	return cfg
}

func (s *Server) serve(ln net.Listener) {
	for {
		c, err := ln.Accept()
		if err != nil {
			return
		}
		s.mu.Lock()
		s.conns[c] = true
		s.mu.Unlock()
		go s.handleConn(c)
	}
}

func (s *Server) handleConn(c net.Conn) {
	defer func() {
		c.Close() //nolint:errcheck,gosec
		s.mu.Lock()
		delete(s.conns, c)
		s.mu.Unlock()
	}()
	sc, chans, reqs, err := ssh.NewServerConn(c, s.config())
	if err != nil {
		return
	}
	s.mu.Lock()
	s.logins = append(s.logins, sc.User())
	s.mu.Unlock()
	go func() {
		for r := range reqs {
			if s.IgnoreKeepalive.Load() {
				continue // never reply
			}
			if r.WantReply {
				r.Reply(false, nil) //nolint:errcheck,gosec // OpenSSH replies failure to keepalive@openssh.com
			}
		}
	}()
	for nc := range chans {
		switch nc.ChannelType() {
		case "session":
			go s.handleSession(nc)
		case "direct-tcpip":
			go s.handleDirect(nc)
		default:
			nc.Reject(ssh.UnknownChannelType, "unsupported") //nolint:errcheck,gosec
		}
	}
}

func (s *Server) track(delta int) {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.open += delta
	if s.open > s.maxOpen {
		s.maxOpen = s.open
	}
}

func (s *Server) handleSession(nc ssh.NewChannel) {
	ch, reqs, err := nc.Accept()
	if err != nil {
		return
	}
	s.track(1)
	defer s.track(-1)
	defer ch.Close() //nolint:errcheck
	for r := range reqs {
		if r.Type != "exec" {
			if r.WantReply {
				r.Reply(false, nil) //nolint:errcheck,gosec
			}
			continue
		}
		var payload struct{ Cmd string }
		if err := ssh.Unmarshal(r.Payload, &payload); err != nil {
			r.Reply(false, nil) //nolint:errcheck,gosec
			return
		}
		r.Reply(true, nil) //nolint:errcheck,gosec
		s.mu.Lock()
		s.execs = append(s.execs, payload.Cmd)
		s.mu.Unlock()
		status := 127
		if s.Exec != nil {
			status = s.Exec(payload.Cmd, ch, ch, ch.Stderr())
		}
		ch.CloseWrite() //nolint:errcheck,gosec
		b := make([]byte, 4)
		binary.BigEndian.PutUint32(b, uint32(status)) //nolint:gosec // exit status fits
		ch.SendRequest("exit-status", false, b)       //nolint:errcheck,gosec
		return
	}
}

func (s *Server) handleDirect(nc ssh.NewChannel) {
	if !s.AllowForwarding {
		nc.Reject(ssh.Prohibited, "administratively prohibited: port forwarding is disabled") //nolint:errcheck,gosec
		return
	}
	var p struct {
		Host       string
		Port       uint32
		OriginHost string
		OriginPort uint32
	}
	if err := ssh.Unmarshal(nc.ExtraData(), &p); err != nil {
		nc.Reject(ssh.ConnectionFailed, "bad payload") //nolint:errcheck,gosec
		return
	}
	dial := s.DialTarget
	if dial == nil {
		dial = func(a string) (net.Conn, error) { return net.Dial("tcp", a) }
	}
	target, err := dial(net.JoinHostPort(p.Host, strconv.Itoa(int(p.Port))))
	if err != nil {
		nc.Reject(ssh.ConnectionFailed, fmt.Sprintf("connect failed: %v", err)) //nolint:errcheck,gosec
		return
	}
	ch, reqs, err := nc.Accept()
	if err != nil {
		target.Close() //nolint:errcheck,gosec
		return
	}
	s.track(1)
	go ssh.DiscardRequests(reqs)
	var wg sync.WaitGroup
	wg.Add(2)
	go func() { defer wg.Done(); io.Copy(ch, target); ch.CloseWrite() }() //nolint:errcheck,gosec
	go func() { defer wg.Done(); io.Copy(target, ch); target.Close() }()  //nolint:errcheck,gosec
	wg.Wait()
	ch.Close() //nolint:errcheck,gosec
	s.track(-1)
}
